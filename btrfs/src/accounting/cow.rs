//! Convert references in parent-before-child order. A shared block abandoned
//! by its owner retains explicit parent references for its outgoing pointers;
//! the writing tree retains or acquires its own implicit references.

use alloc::vec::Vec;

use core::cmp::Reverse;

use super::{Accounting, DataChange, MetadataBlock};
use crate::allocation::MetadataReference;
use crate::allocation::data::{DataBackref, DataReference, SharedDataReference};
use crate::items::FileExtent;
use crate::ondisk::{RawFileExtentBody, RawFileExtentHead, item_type, view};
use crate::source::BlockSource;
use crate::space::Space;
use crate::tree::write::{Trees, WriteError};
use crate::tree::{Expected, Node};
use crate::volume::Volume;
use crate::{Error, Key};

trait References {
    type Data: DataBackref;
    fn metadata(&self) -> MetadataReference;
    fn data(&self, inode: u64, offset: u64) -> Self::Data;
}

struct RootReferences(u64);
struct ParentReferences(u64);

impl References for RootReferences {
    type Data = DataReference;
    fn metadata(&self) -> MetadataReference {
        MetadataReference::root(self.0)
    }
    fn data(&self, inode: u64, offset: u64) -> DataReference {
        DataReference {
            root: self.0,
            inode,
            offset,
        }
    }
}

impl References for ParentReferences {
    type Data = SharedDataReference;
    fn metadata(&self) -> MetadataReference {
        MetadataReference::parent(self.0)
    }
    fn data(&self, _: u64, _: u64) -> SharedDataReference {
        SharedDataReference(self.0)
    }
}

impl Accounting {
    /// Drain committed-block retirements, including those generated by updating
    /// the accounting trees themselves. An error invalidates the transaction.
    pub(crate) async fn sync_references<S: BlockSource>(
        &mut self,
        volume: &Volume<S>,
        trees: &mut Trees,
        space: &mut Space,
    ) -> Result<(), WriteError> {
        while self.processed_retired < trees.retired().len() {
            let end = trees.retired().len();
            let mut batch: Vec<_> = trees
                .retired()
                .iter()
                .skip(self.processed_retired)
                .take(end - self.processed_retired)
                .copied()
                .collect();
            batch.sort_by_key(|block| Reverse(block.level));
            for retired in batch {
                let block = MetadataBlock {
                    address: retired.address,
                    level: retired.level,
                };
                let (_, extent) = self.metadata(volume, trees, block).await?;
                let node = Node::read(
                    volume,
                    retired.address,
                    Expected {
                        level: retired.level,
                        generation: retired.generation,
                        first_key: None,
                    },
                )
                .await?;
                if extent.references() > 1 {
                    if node.owner() == retired.tree && !extent.full_backrefs() {
                        self.change_children(
                            volume,
                            trees,
                            space,
                            &node,
                            ParentReferences(retired.address),
                            true,
                        )
                        .await?;
                        self.set_full_backrefs(volume, trees, space, block).await?;
                    } else {
                        self.change_children(
                            volume,
                            trees,
                            space,
                            &node,
                            RootReferences(retired.tree),
                            true,
                        )
                        .await?;
                    }
                } else if extent.full_backrefs() {
                    self.change_children(
                        volume,
                        trees,
                        space,
                        &node,
                        RootReferences(retired.tree),
                        true,
                    )
                    .await?;
                    self.change_children(
                        volume,
                        trees,
                        space,
                        &node,
                        ParentReferences(retired.address),
                        false,
                    )
                    .await?;
                }
                self.remove_metadata(
                    volume,
                    trees,
                    space,
                    block,
                    MetadataReference::root(retired.tree),
                )
                .await?;
            }
            self.processed_retired = end;
        }
        Ok(())
    }

    async fn change_children<S: BlockSource, R: References>(
        &mut self,
        volume: &Volume<S>,
        trees: &mut Trees,
        space: &mut Space,
        node: &Node,
        references: R,
        add: bool,
    ) -> Result<(), WriteError> {
        for slot in 0..node.nritems() {
            if node.level() > 0 {
                let block = MetadataBlock {
                    address: node.child(slot).0,
                    level: node.level() - 1,
                };
                if add {
                    self.add_metadata(volume, trees, space, block, references.metadata())
                        .await?;
                } else {
                    self.remove_metadata(volume, trees, space, block, references.metadata())
                        .await?;
                }
                continue;
            }
            let key = node.key(slot);
            if key.item_type != item_type::EXTENT_DATA {
                continue;
            }
            let bytes = node.item(slot);
            FileExtent::parse(key, bytes, volume.superblock().sectorsize()).map_err(|defect| {
                Error::Item {
                    tree: node.owner(),
                    key,
                    defect,
                }
            })?;
            let head: &RawFileExtentHead = view(bytes).expect("validated file extent");
            if head.extent_type == 0 {
                continue;
            } // BTRFS_FILE_EXTENT_INLINE.
            let body: &RawFileExtentBody =
                view(&bytes[size_of::<RawFileExtentHead>()..]).expect("validated file extent body");
            if body.disk_bytenr.get() == 0 {
                continue;
            }
            // btrfs' unsigned offset subtraction intentionally wraps for a
            // clone whose referenced extent offset exceeds its file offset.
            let offset = key.offset.wrapping_sub(body.offset.get());
            let change = DataChange {
                key: Key::new(
                    body.disk_bytenr.get(),
                    item_type::EXTENT_ITEM,
                    body.disk_num_bytes.get(),
                ),
                reference: references.data(key.objectid, offset),
                delta: if add { 1 } else { -1 },
            };
            self.update_data(volume, trees, space, change).await?;
        }
        Ok(())
    }
}
